import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';

import 'core/theme.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'repositories/attendance_repository.dart';
import 'repositories/auth_repository.dart';
import 'repositories/employee_repository.dart';
import 'repositories/profile_request_repository.dart';
import 'viewmodels/auth_viewmodel.dart';
import 'views/auth/login_view.dart';
import 'views/employee/employee_shell.dart';
import 'views/hr/hr_shell.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const AttendanceApp());
}

class AttendanceApp extends StatelessWidget {
  const AttendanceApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MultiProvider(
      providers: [
        Provider<AuthRepository>(create: (_) => AuthRepository()),
        Provider<AttendanceRepository>(create: (_) => AttendanceRepository()),
        Provider<EmployeeRepository>(create: (_) => EmployeeRepository()),
        // FIX: EmployeeShell and HrShell both call
        // context.read<ProfileRequestRepository>(). Without this provider
        // the app throws ProviderNotFoundException as soon as either shell
        // is built.
        Provider<ProfileRequestRepository>(
          create: (_) => ProfileRequestRepository(),
        ),
        ChangeNotifierProvider<AuthViewModel>(
          create: (ctx) => AuthViewModel(ctx.read<AuthRepository>()),
        ),
      ],
      child: MaterialApp(
        title: 'QR Attendance',
        debugShowCheckedModeBanner: false,
        theme: buildTheme(),
        home: const AuthGate(),
      ),
    );
  }
}

/// Chooses the screen by auth state and role.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    final auth = context.watch<AuthViewModel>();

    if (auth.initializing) {
      return const Scaffold(body: Center(child: CircularProgressIndicator()));
    }
    final user = auth.user;
    if (user == null) return const LoginView();
    if (user.isHr) return HrShell(key: ValueKey(user.uid), hr: user);
    return EmployeeShell(key: ValueKey(user.uid), user: user);
  }
}
